import numpy as np
import matplotlib.pyplot as plt
from scipy.stats import beta

alpha_0, beta_0 = 2, 8

n1, k1 = 20, 5
alpha_1 = alpha_0 + k1
beta_1 = beta_0 + (n1 - k1)
media_1 = alpha_1 / (alpha_1 + beta_1)

print(f"(a) A posteriori după lotul 1: Beta({alpha_1}, {beta_1})")
print(f"    Media a posteriori: {media_1:.4f}")

n2, k2 = 15, 3

alpha_b = alpha_1 + k2
beta_b = beta_1 + (n2 - k2)
media_b = alpha_b / (alpha_b + beta_b)
var_b = beta.var(alpha_b, beta_b)

print(f"\n(b) A posteriori după ambele loturi: Beta({alpha_b}, {beta_b})")
print(f"    Media: {media_b:.4f} (2/9), Varianța: {var_b:.6f}")

alpha_c = alpha_0 + k2
beta_c = beta_0 + (n2 - k2)
media_c = alpha_c / (alpha_c + beta_c)
var_c = beta.var(alpha_c, beta_c)

print(f"\n(c) A posteriori doar cu lotul 2: Beta({alpha_c}, {beta_c})")
print(f"    Media: {media_c:.4f} (1/5), Varianța: {var_c:.6f}")

theta = np.linspace(0, 1, 500)
pdf_prior = beta.pdf(theta, alpha_0, beta_0)
pdf_post1 = beta.pdf(theta, alpha_1, beta_1)

plt.figure(figsize=(8, 4.5))
plt.plot(theta, pdf_prior, "--", color="#1f77b4", lw=2, label=f"A priori: Beta({alpha_0}, {beta_0}) [medie = 0.200]")
plt.fill_between(theta, pdf_prior, color="#1f77b4", alpha=0.12)

plt.plot(theta, pdf_post1, "-", color="#d62728", lw=2.5, label=f"A posteriori: Beta({alpha_1}, {beta_1}) [medie = {media_1:.3f}]")
plt.fill_between(theta, pdf_post1, color="#d62728", alpha=0.18)

plt.axvline(alpha_0 / (alpha_0 + beta_0), color="#1f77b4", linestyle=":", lw=1.5)
plt.axvline(media_1, color="#d62728", linestyle=":", lw=1.5)

plt.title("Subiectul 3(a): Densitățile a priori și a posteriori pentru $\\theta$")
plt.xlabel("$\\theta$ (probabilitatea de defect)")
plt.ylabel("Densitatea de probabilitate")
plt.xlim(0, 0.8)
plt.grid(True, linestyle="--", alpha=0.4)
plt.legend()
plt.tight_layout()
plt.savefig("inferenta_bayesiana_ex3.png", dpi=150, bbox_inches="tight")
plt.show()