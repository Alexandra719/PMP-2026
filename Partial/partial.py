#Subiectul 1

import numpy as np
from hmmlearn import hmm

pi = np.array([0.25, 0.25, 0.25, 0.25])

B = np.array([
    [0.7, 0.2, 0.1],
    [0.2, 0.6, 0.2],
    [0.1, 0.3, 0.6],
    [0.5, 0.2, 0.3],
])

obs = np.array([[0], [1], [2], [2], [0]])

def rezolva_hmm(A, nume_subpunct):
    model = hmm.CategoricalHMM(n_components=4)
    model.startprob_ = pi
    model.transmat_ = A
    model.emissionprob_ = B

    log_prob, states = model.decode(obs, algorithm="viterbi")
    prob = np.exp(log_prob)
    camere = states + 1

    print(f"{nume_subpunct}")
    print(f"Cea mai probabilă secvență de camere: {camere.tolist()}")
    print(f"Probabilitatea comună P(X, O): {prob:.9f}\n")

A_a = np.array([
    [0.2, 0.4, 0.0, 0.4],
    [0.4, 0.2, 0.4, 0.0],
    [0.0, 0.4, 0.2, 0.4],
    [0.4, 0.0, 0.4, 0.2],
])

A_b = np.array([
    [0.0, 0.5, 0.0, 0.5],
    [0.5, 0.0, 0.5, 0.0],
    [0.0, 0.5, 0.0, 0.5],
    [0.5, 0.0, 0.5, 0.0],
])

rezolva_hmm(A_a, "Subpunctul a")
rezolva_hmm(A_b, "Subpunctul b")

import networkx as nx
import matplotlib.pyplot as plt

fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(11, 4))

G_a = nx.Graph()
G_a.add_edges_from([('A', 'B'), ('B', 'C'), ('C', 'D'), ('D', 'E')])
pos_a = {'A': (0, 0), 'B': (1, 0), 'C': (2, 0), 'D': (3, 0), 'E': (4, 0)}

nx.draw(
    G_a, pos_a, ax=ax1, with_labels=True,
    node_size=1600, node_color='#D6EAF8', edgecolors='#1B4F72',
    font_size=13, font_weight='bold', width=2
)
ax1.set_title("(a) Rețea Markov: lanț A - B - C - D - E", fontsize=11, pad=12)

G_b = nx.Graph()
G_b.add_edges_from([('A', 'B'), ('B', 'C'), ('A', 'C'), ('B', 'D'), ('C', 'E')])
pos_b = {'A': (0, 0.5), 'B': (1, 1), 'C': (1, 0), 'D': (2.2, 1), 'E': (2.2, 0)}

nx.draw(
    G_b, pos_b, ax=ax2, with_labels=True,
    node_size=1600, node_color='#D5F5E3', edgecolors='#145A32',
    font_size=13, font_weight='bold', width=2
)
ax2.set_title("(b) Rețea Markov: clica {A, B, C} + (B, D), (C, E)", fontsize=11, pad=12)

plt.tight_layout()
plt.savefig("retele_markov_ex2.png", dpi=150, bbox_inches="tight")
plt.show()

